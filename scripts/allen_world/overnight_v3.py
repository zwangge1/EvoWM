"""Snapshot-based, bounded two-level Allen experiment launcher for Linux.

Default smoke runs are plumbing checks, not scientific calibration. --full
requests the development matrix. GPUs must be selected explicitly. No inputs
are regenerated in place, and a resumed run uses its original frozen inputs.
Exit codes: 0 all planned jobs complete, 1 failed, 2 incomplete, 3 invalid run.
"""
