HERE = Path(__file__).resolve().parent
VARIANTS = ("full", "no_link", "scalar", "supervised", "single")
CONFIGS = {v: "allen_v3_" + v for v in VARIANTS}
COMPARISONS = {
    "no_link": "Does upper-state conditioning improve allocation? The control still reconstructs bones from upper predicted total.",
    "scalar": "Does the rich upper latent improve prediction beyond a predicted total scalar?",
    "supervised": "Do the latent prediction and SIGReg objectives improve the same two-level network?",
    "single": "Does the two-level model improve on the capacity-matched single-level model?",
}
SCENARIOS = ("null", "motion", "temperature", "joint", "equal", "reverse")
STAGES = ("simulation", "real_development")
PLAN_FIELDS = ("mode", "variants", "scenarios", "seeds", "folds", "stages", "sim_steps", "real_steps")
THREAD_KEYS = ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS", "NUMEXPR_NUM_THREADS")


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save_json(path, value):
    path = Path(path)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8")
    os.replace(temp, path)


def code_hashes(root=ROOT):
    root = Path(root)
    patterns = [("src/evowm", "*.py"), ("scripts/allen_world", "*.py"),
                ("scripts/allen_world", "*.sh"), ("configs/hjepa", "*.yaml"),
                ("hjepa/h_jepa", "*.py"), ("tests", "test_allen*.py")]
    paths = {root / "scripts/train_hjepa.sh", root / "environment.yml"}
    for folder, pattern in patterns:
        paths.update((root / folder).rglob(pattern))
    return {p.relative_to(root).as_posix(): digest(p) for p in sorted(paths) if p.is_file()}


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    modes = p.add_mutually_exclusive_group()
    modes.add_argument("--smoke", dest="mode", action="store_const", const="smoke")
    modes.add_argument("--full", dest="mode", action="store_const", const="full")
    p.add_argument("--gpus", nargs="+", required=True)
    p.add_argument("--hours", type=float, default=8.)
    p.add_argument("--variants", nargs="+", choices=tuple(CONFIGS))
    p.add_argument("--scenarios", nargs="+", choices=SCENARIOS)
    p.add_argument("--seeds", nargs="+", type=int)
    p.add_argument("--folds", nargs="+", type=int)
    p.add_argument("--stages", nargs="+", choices=STAGES)
    p.add_argument("--sim-steps", type=int)
    p.add_argument("--real-steps", type=int)
    p.add_argument("--eval-workers", type=int, default=32)
    p.add_argument("--loader-workers", type=int, default=8)
    p.add_argument("--threads-per-job", type=int, default=4)
    p.add_argument("--job-timeout-minutes", type=float, default=90.)
